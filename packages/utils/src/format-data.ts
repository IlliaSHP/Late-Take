// Intl.DateTimeFormat — вбудований у JavaScript конструктор, який створює об'єкт-форматер дат.
// Перший аргумент — локаль ('en-US'): мова й регіон, за правилами яких форматується дата
// (мова назв місяців, порядок частин, роздільники).
// Другий аргумент — опції: які частини дати показувати і в якому вигляді.
//
// Форматер створюється один раз на рівні модуля, а не всередині функції.
// Створення Intl.DateTimeFormat відносно дороге, бо треба завантажити дані локалі
// й розібрати опції. Тому його створюють один раз, а потім перевикористовують
// при кожному виклику formatDate. Це називається кешуванням форматера.
const DATE_FORMAT = new Intl.DateTimeFormat('en-US', {
  day: 'numeric',   // день числом: 12
  month: 'short',   // місяць скорочено: Oct
  year: 'numeric'   // рік повністю: 2026
})
// Результат для цих опцій: "Oct 12, 2026".
// Порядок частин і кома визначаються локаллю, а не порядком ключів в об'єкті.

// Приймає дату рядком (наприклад, ISO-рядок з API: '2026-10-12T08:00:00Z')
// і повертає її у вигляді "Oct 12, 2026".
export function formatDate(date: string) {
  // new Date(date) розбирає рядок і створює об'єкт Date.
  // DATE_FORMAT.format(...) — метод форматера: приймає об'єкт Date
  // і повертає рядок, відформатований за локаллю та опціями, заданими вище.
  return DATE_FORMAT.format(new Date(date))
}